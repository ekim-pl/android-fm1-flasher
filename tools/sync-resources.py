#!/usr/bin/env python3
"""Regenerate resource-key bridges; Android XML remains authoritative during migration."""
from pathlib import Path
import argparse
import json
import re
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

def strings(folder):
    return {item.attrib['name']: ''.join(item.itertext()).replace('\\n', '\n').replace("\\'", "'").replace("\\u0020", " ")
            for path in sorted((root / f'app/src/main/res/{folder}').glob('*.xml'))
            for item in ET.parse(path).getroot()
            if item.tag == 'string'}

def write(relative, text):
    path = root / relative
    if args.check:
        if path.read_text() != text:
            raise SystemExit(f'{relative} is stale; run python3 tools/sync-resources.py')
    else:
        path.write_text(text)

names = list(strings('values'))
write('app/src/main/java/pl/ekim/fm1_flasher/ResourceKeys.kt',
      'package pl.ekim.fm1_flasher\n\n// Generated by tools/sync-resources.py.\ninternal val androidResourceKeys = mapOf(\n'
      + ''.join(f'    R.string.{name} to "{name}",\n' for name in names)
      + ')\ninternal val androidResourceIds = androidResourceKeys.entries.associate { it.value to it.key }\n')
keys = set(names)
text = 'package pl.ekim.fm1_flasher\n\n// Generated by tools/sync-resources.py.\ninternal val coreStrings = mapOf(\n'
for language, folder in [('en', 'values'), ('pl', 'values-pl'), ('zh', 'values-b+zh+Hans')]:
    translations = strings(folder)
    text += f'    "{language}" to mapOf(\n'
    for key in sorted(keys):
        value = json.dumps(translations[key], ensure_ascii=False).replace('$', '\\$')
        text += f'        "{key}" to {value},\n'
    text += '    ),\n'
text += ')\n'
write('composeApp/src/commonMain/kotlin/pl/ekim/fm1_flasher/CoreStrings.kt', text)
